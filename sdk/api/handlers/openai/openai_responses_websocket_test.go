type websocketFailoverSelector struct {
	mu    sync.Mutex
	order []string
	picks int
}

type websocketPinnedFailoverExecutor struct {
	mu       sync.Mutex
	authIDs  []string
	calls    map[string]int
	payloads map[string][][]byte
}

func (s *websocketFailoverSelector) Pick(
	_ context.Context,
	_, _ string,
	_ coreexecutor.Options,
	auths []*coreauth.Auth,
) (*coreauth.Auth, error) {
	if len(auths) == 0 {
		return nil, errors.New("no auth")
	}
	s.mu.Lock()
	idx := s.picks
	if idx >= len(s.order) {
		idx = len(s.order) - 1
	}
	wanted := s.order[idx]
	s.picks++
	s.mu.Unlock()
	for _, auth := range auths {
		if auth != nil && auth.ID == wanted {
			return auth, nil
		}
	}
	return auths[0], nil
}

