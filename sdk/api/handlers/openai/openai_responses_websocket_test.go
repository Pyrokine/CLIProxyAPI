func (e *websocketPinnedFailoverExecutor) ExecuteStream(
	_ context.Context,
	auth *coreauth.Auth,
	req coreexecutor.Request,
	_ coreexecutor.Options,
) (*coreexecutor.StreamResult, error) {
	authID := ""
	if auth != nil {
		authID = auth.ID
	}

	e.mu.Lock()
	if e.calls == nil {
		e.calls = make(map[string]int)
	}
	if e.payloads == nil {
		e.payloads = make(map[string][][]byte)
	}
	e.authIDs = append(e.authIDs, authID)
	e.calls[authID]++
	call := e.calls[authID]
	e.payloads[authID] = append(e.payloads[authID], bytes.Clone(req.Payload))
	e.mu.Unlock()

	chunks := make(chan coreexecutor.StreamChunk, 2)
	chunks <- coreexecutor.StreamChunk{Payload: []byte(`{"type":"response.created"}`)}
	if authID == "auth-a" && call == 2 {
		chunks <- coreexecutor.StreamChunk{
			Err: &coreauth.Error{
				Code:       "rate_limit_exceeded",
				Message:    "quota exhausted",
				HTTPStatus: http.StatusTooManyRequests,
			},
		}
		close(chunks)
		return &coreexecutor.StreamResult{Chunks: chunks}, nil
	}
	chunks <- coreexecutor.StreamChunk{
		Payload: []byte(fmt.Sprintf(
			`{"type":"response.completed","response":{"id":"resp-%s-%d","output":[{"type":"message","id":"out-%s-%d"}]}}`,
			authID, call, authID, call,
		)),
	}
	close(chunks)
	return &coreexecutor.StreamResult{Chunks: chunks}, nil
}

